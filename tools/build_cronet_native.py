#!/usr/bin/env python3
"""Build the platform Cronet library, libmainlinecronet.<version>.so, from AOSP's external/cronet.

The framework's android.net.http.HttpEngine is the Tethering module's Cronet: its Java half, jarjar'd under
android.net.connectivity and generated by generate_cronet_java.py from the same tree, is in framework.jar and
loads libmainlinecronet.<version>.so. Westlake had only the Java half, so HttpEngine fell back to Java Cronet,
which has no bidirectional streams; Google's Play Store has no other native engine and could not reach its
servers.

This builds the native half as Soong builds it for an arm64 device, from external/cronet's generated Blueprint
(gn2bp): the closure of cronet_aml_components_cronet_android_cronet, its genrules (build flags, JNI headers
with the android.net.connectivity package prefix, protobuf), every source compiled with Chromium's clang
against the NDK sysroot (Bionic, API 29) and Chromium's own libc++ (stl: none), and one shared library linked
from the module archives. It differs from the APEX build in two places, both so that the library stands alone:
BoringSSL (libcrypto, libssl, libpki) is linked in statically, and protobuf-lite is Cronet's own copy (3.20.3,
the version its protoc generates) instead of the platform's libprotobuf-cpp-lite.

Sources the clang 16 toolchain cannot compile as written get a small source fix from native/cronet-patches
(--patches), applied to a copy of each touched file in the output tree; external/cronet itself is not changed.

usage: build_cronet_native.py --cronet <external/cronet> --ndk <android_ndk> --llvm <clang bin dir>
                              --protoc <host protoc 3.20.x> --javap <JDK javap> --android-jar <android.jar>
                              --ninja <ninja> --out <dir> [--patches <dir>] [--jobs N] [--plan-only]
"""
import argparse
import collections
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from aosp_blueprint import tokens, value, expr  # noqa: E402


def evaluate(x, env):
    """Blueprint values: variables and + as aosp_blueprint reads them, and maps (target: {...}) recursively."""
    if isinstance(x, list):
        return [evaluate(v, env) for v in x]
    if isinstance(x, dict):
        if set(x) == {'variable'}:
            return evaluate(env[x['variable']], env)
        if set(x) == {'add'}:
            a, b = x['add']
            return evaluate(a, env) + evaluate(b, env)
        return {k: evaluate(v, env) for k, v in x.items()}
    return x

TARGET = 'cronet_aml_components_cronet_android_cronet'
API = 29
# Soong variant blocks that apply to an arm64 Android device build. Android is a Linux OS to Soong, so
# target.linux applies too (BoringSSL adds its assembly there).
TARGET_VARIANTS = ('android', 'android_arm64', 'bionic', 'bionic_arm64', 'linux', 'linux_arm64', 'not_windows')
ARCH_VARIANTS = ('arm64',)
DEPS = ('static_libs', 'whole_static_libs', 'shared_libs', 'header_libs')
GEN = ('generated_headers', 'generated_sources')
# Platform libraries the APEX links dynamically; the NDK provides them. BoringSSL and protobuf-lite are built in.
PLATFORM = {'liblog': 'log', 'libandroid': 'android', 'libmediandk': 'mediandk', 'libz': 'z', 'libdl': 'dl',
            'libc': 'c', 'libm': 'm', 'jni_headers': None, 'libgtest_prod_headers': None}
SUBSTITUTE = {'libprotobuf-cpp-lite': 'cronet_aml_third_party_protobuf_protobuf_lite'}


class Blueprint:
    """external/cronet's modules, keyed by (directory relative to the tree, name)."""

    def __init__(self, root):
        self.root = root
        self.modules = {}
        files = [root / 'Android.bp', root / 'Android.extras.bp']
        for nested in sorted(root.rglob('Android.bp')):
            if nested.parent != root and '.git' not in nested.parts:
                files.append(nested)
        pending = [f for f in files if f.is_file()]
        seen = set()
        while pending:
            path = pending.pop(0)
            if path in seen:
                continue
            seen.add(path)
            rel = path.parent.relative_to(root).as_posix()
            ts = tokens(path.read_text())
            i = 0
            env = {}
            while i < len(ts):
                name, op = ts[i], ts[i + 1]
                i += 2
                if op == '{':
                    fields, i = value(ts, i - 1)
                    if isinstance(fields.get('name'), str):
                        self.modules[(rel, fields['name'])] = {'kind': name, 'fields': fields, 'env': dict(env),
                                                                'dir': rel}
                elif op == '=':
                    env[name], i = expr(ts, i)
                elif op == '+' and ts[i] == '=':
                    x, i = expr(ts, i + 1)
                    env[name] = {'add': [env[name], x]}
            for pattern in evaluate(env.get('build', []), env):
                pending.extend(sorted(path.parent.glob(pattern)))
        self.by_name = collections.defaultdict(list)
        for key in self.modules:
            self.by_name[key[1]].append(key)

    def resolve(self, ref, here='.'):
        ref = SUBSTITUTE.get(ref, ref)
        if ref.startswith('//external/cronet'):
            path, _, name = ref[len('//external/cronet'):].lstrip('/').partition(':')
            key = (path or '.', name)
            return key if key in self.modules else None
        if (here, ref) in self.modules:
            return (here, ref)
        keys = self.by_name.get(ref, [])
        return keys[0] if len(keys) == 1 else None


def merge(into, extra):
    for key, val in extra.items():
        if key in ('target', 'arch', 'multilib'):
            continue
        if isinstance(val, list):
            into[key] = into.get(key, []) + val
        elif isinstance(val, dict) and isinstance(into.get(key), dict):
            merged = dict(into[key])
            merge(merged, val)
            into[key] = merged
        else:
            into[key] = val


class Module:
    """One module's properties for the device arm64 variant, defaults first, as Soong merges them."""

    def __init__(self, bp, key):
        self.key = key
        self.name = key[1]
        raw = bp.modules[key]
        self.kind = raw['kind']
        self.dir = raw['dir']
        self.props = {}
        for default in raw['fields'].get('defaults', []):
            dkey = bp.resolve(default, self.dir)
            if dkey is None:
                raise ValueError('Missing defaults ' + default + ' of ' + self.name)
            merge(self.props, Module(bp, dkey).props)
        fields = evaluate(raw['fields'], raw['env'])
        merge(self.props, fields)
        for scope, names in (('target', TARGET_VARIANTS), ('arch', ARCH_VARIANTS), ('multilib', ('lib64',))):
            blocks = fields.get(scope) or {}
            for variant in names:
                if variant in blocks:
                    merge(self.props, blocks[variant])

    def get(self, key):
        return self.props.get(key, [])


def closure(bp):
    start = bp.resolve(TARGET)
    seen, order, todo, platform = {}, [], [start], set()
    while todo:
        key = todo.pop()
        if key in seen:
            continue
        module = Module(bp, key)
        seen[key] = module
        order.append(key)
        refs = []
        for field in DEPS + GEN + ('export_generated_headers',):
            refs += module.get(field)
        refs += [s[1:] for s in module.get('srcs') if isinstance(s, str) and s.startswith(':')]
        for ref in refs:
            if ref in PLATFORM:
                platform.add(ref)
                continue
            dep = bp.resolve(ref, key[0])
            if dep is None:
                raise ValueError('Unresolved dependency ' + ref + ' of ' + module.name)
            if dep not in seen:
                todo.append(dep)
    return seen, order, platform


class Build:
    def __init__(self, args):
        self.args = args
        self.cronet = args.cronet.resolve()
        self.out = args.out.resolve()
        self.bp = Blueprint(self.cronet)
        self.modules, self.order, self.platform = closure(self.bp)
        self.top = self.out / 'top'
        self.sysroot = args.ndk.resolve() / 'toolchains/llvm/prebuilt/linux-x86_64/sysroot'
        self.llvm = args.llvm.resolve()
        self.overlay = self.out / 'overlay'
        self.patched = set()

    def apply_patches(self):
        """Westlake's patches (native/cronet-patches), applied to copies of the files they touch: the import
        stays as AOSP ships it, patched sources compile from the overlay, and the overlay leads the includes."""
        import shutil
        if self.overlay.exists():
            shutil.rmtree(self.overlay)
        self.overlay.mkdir(parents=True)
        for patch in sorted(self.args.patches.glob('*.patch')):
            touched = re.findall(r'^\+\+\+ b/(\S+)', patch.read_text(), re.M)
            for rel in touched:
                target = self.overlay / rel
                target.parent.mkdir(parents=True, exist_ok=True)
                if not target.exists():
                    shutil.copyfile(self.cronet / rel, target)
                # A source includes its own header by a relative quote ("x.h"), found beside it first: the
                # copy needs its directory's headers beside it too.
                for header in (self.cronet / rel).parent.glob('*.h'):
                    if not (target.parent / header.name).exists():
                        shutil.copyfile(header, target.parent / header.name)
                self.patched.add(rel)
            subprocess.run(['patch', '-p1', '-s', '-d', str(self.overlay), '-i', str(patch)], check=True)
        print('patches applied:', len(list(self.args.patches.glob('*.patch'))), sorted(self.patched))

    # -- paths -------------------------------------------------------------------------------------------------
    def src(self, module, path):
        """A path a module names: relative to its directory, or to the tree top for external/cronet/..."""
        if path.startswith('external/cronet/'):
            return self.cronet / path[len('external/cronet/'):]
        return self.cronet / module.dir / path

    def gen_dir(self, name):
        return self.out / 'gen' / name

    def outputs(self, name):
        module = self.modules[self.bp.resolve(name)]
        return [self.gen_dir(name) / o for o in module.get('out')]

    def filegroup(self, module):
        files = []
        for s in module.get('srcs'):
            if s.startswith(':'):
                files += self.sources(self.modules[self.bp.resolve(s[1:], module.dir)])
            else:
                files.append(self.src(module, s))
        return files

    def sources(self, module):
        """A module's compiled sources: its own files, filegroups and genrule outputs."""
        files = []
        for s in module.get('srcs'):
            if s.startswith(':'):
                dep = self.modules[self.bp.resolve(s[1:], module.dir)]
                files += self.outputs(dep.name) if 'genrule' in dep.kind else self.filegroup(dep)
            elif any(c in s for c in '*?['):
                files += sorted((self.cronet / module.dir).glob(s))
            else:
                files.append(self.src(module, s))
        for g in module.get('generated_sources'):
            files += self.outputs(g)
        excluded = {self.src(module, e) for e in module.get('exclude_srcs')}
        out = []
        for f in files:
            if f in excluded or f.suffix not in ('.c', '.cc', '.cpp', '.S', '.s'):
                continue
            if f.is_relative_to(self.cronet) and f.relative_to(self.cronet).as_posix() in self.patched:
                f = self.overlay / f.relative_to(self.cronet)
            out.append(f)
        return out

    # -- includes ----------------------------------------------------------------------------------------------
    def exported(self, key, stack=()):
        module = self.modules[key]
        dirs = []
        if 'genrule' in module.kind:
            # Soong exports each of a genrule's export_include_dirs twice: under its gen directory plus its
            # module directory (genDir/external/cronet/<dir>, where protoc's --cpp_out writes) and under the
            # gen directory alone (genDir/<dir>, where the build-flag headers go).
            base = self.gen_dir(module.name)
            exports = module.get('export_include_dirs')
            moddir = base / 'external' / 'cronet' / ('' if module.dir == '.' else module.dir)
            return [p for d in exports for p in (moddir / d, base / d)] if exports else [base]
        dirs += [self.cronet / module.dir / d for d in module.get('export_include_dirs')]
        dirs += [self.cronet / module.dir / d for d in module.get('export_system_include_dirs')]
        for g in module.get('export_generated_headers'):
            dirs += self.exported(self.bp.resolve(g, module.dir), stack + (key,))
        for field in ('export_static_lib_headers', 'export_header_lib_headers', 'export_shared_lib_headers'):
            for ref in module.get(field):
                dep = self.bp.resolve(ref, module.dir)
                if dep and dep not in stack and dep in self.modules:
                    dirs += self.exported(dep, stack + (key,))
        return dirs

    def includes(self, module):
        dirs = [self.cronet / module.dir / d for d in module.get('local_include_dirs')]
        dirs += [self.src(module, d) for d in module.get('include_dirs')]
        for field in DEPS + ('generated_headers',):
            for ref in module.get(field):
                if ref in PLATFORM:
                    continue
                dep = self.bp.resolve(ref, module.dir)
                dirs += self.exported(dep)
        seen, out = set(), []
        for d in dirs:
            if d not in seen:
                seen.add(d)
                out.append(d)
        return out

    # -- genrules ----------------------------------------------------------------------------------------------
    def genrule_command(self, module):
        name = module.name
        # Host tools and SDK files outside external/cronet: protobuf's compiler, the JDK's javap, and the
        # Android SDK's android.jar that jni_zero reads standard class signatures from.
        special = {':javap': str(self.args.javap.resolve()), ':current_android_jar': str(self.args.android_jar.resolve())}
        tool_files = {}
        for t in module.get('tool_files'):
            if t in special:
                tool_files[t] = special[t]
            else:
                tool_files[t] = 'external/cronet/' + (module.dir + '/' if module.dir != '.' else '') + t
        tools = {}
        for tool in module.get('tools'):
            if 'protoc' in tool:
                tools[tool] = str(self.args.protoc.resolve())
            elif tool in special:
                tools[tool] = special[tool]
            else:
                raise ValueError('Unknown genrule tool ' + tool + ' in ' + name)
        srcs = []
        for s in module.get('srcs'):
            if s.startswith(':'):
                srcs += [str(p) for p in self.outputs(s[1:])]
            else:
                srcs.append('external/cronet/' + (module.dir + '/' if module.dir != '.' else '') + s)
        outs = [str(p) for p in self.outputs(name)]

        def location(match):
            label = match.group(2)
            if label in tool_files:
                return tool_files[label]
            if label in tools:
                return tools[label]
            if label in special:
                return special[label]
            if label.startswith(':'):
                return ' '.join(str(p) for p in self.outputs(label[1:]))
            rel = 'external/cronet/' + (module.dir + '/' if module.dir != '.' else '') + label
            if rel in srcs:
                return rel
            if label in module.get('out'):  # one of this genrule's own outputs
                return str(self.gen_dir(name) / label)
            raise ValueError('Unknown $(location ' + label + ') in ' + name)

        cmd = module.props.get('cmd', '')
        cmd = cmd.replace('$$', '\0')
        cmd = re.sub(r'\$\((locations?) ([^)]+)\)', location, cmd)
        cmd = cmd.replace('$(genDir)', str(self.gen_dir(name))).replace('$(out)', ' '.join(outs))
        cmd = cmd.replace('$(in)', ' '.join(srcs)).replace('\0', '$')
        if '$(' in cmd:
            raise ValueError('Unexpanded substitution in ' + name + ': ' + cmd[cmd.index('$('):][:60])
        return cmd

    def run_genrules(self):
        self.top.mkdir(parents=True, exist_ok=True)
        link = self.top / 'external' / 'cronet'
        link.parent.mkdir(parents=True, exist_ok=True)
        if not link.exists():
            link.symlink_to(self.cronet)
        genrules = [k for k in self.order if 'genrule' in self.modules[k].kind]
        done = set()

        def deps(key):
            module = self.modules[key]
            refs = [s[1:] for s in module.get('srcs') if s.startswith(':')]
            refs += re.findall(r'\$\(locations? :([^)]+)\)', module.props.get('cmd', ''))
            return [self.bp.resolve(r, module.dir) for r in refs]

        def run(key):
            if key in done:
                return
            for dep in deps(key):
                if dep in self.modules and 'genrule' in self.modules[dep].kind:
                    run(dep)
            module = self.modules[key]
            outs = self.outputs(module.name)
            if outs and all(o.exists() for o in outs):
                done.add(key)
                return
            gen = self.gen_dir(module.name)
            gen.mkdir(parents=True, exist_ok=True)
            # Soong makes each declared output's directory before the command runs; the JNI generator
            # writes into --output-dir without making it.
            for o in outs:
                o.parent.mkdir(parents=True, exist_ok=True)
            env = dict(os.environ, CC_ARCH='arm64', CC_OS='android', LC_ALL='C', TZ='UTC')
            result = subprocess.run(['bash', '-c', self.genrule_command(module)], cwd=self.top, env=env,
                                    capture_output=True, text=True)
            missing = [str(o) for o in outs if not o.exists()]
            if result.returncode or missing:
                raise RuntimeError('genrule ' + module.name + ' failed (' + str(result.returncode) + ')\n'
                                   + result.stdout[-2000:] + result.stderr[-4000:] + '\nmissing: ' + str(missing))
            done.add(key)

        for key in genrules:
            run(key)
        print('genrules run:', len(done))

    # -- compile and link --------------------------------------------------------------------------------------
    def flags(self, module, language):
        common = ['--target=aarch64-linux-android%d' % API, '--sysroot=' + str(self.sysroot), '-fPIC', '-DANDROID',
                  '-ffunction-sections', '-fdata-sections', '-fno-short-enums', '-fstack-protector-strong',
                  '-no-canonical-prefixes', '-w', '-ffile-prefix-map=' + str(self.cronet) + '=external/cronet',
                  '-ffile-prefix-map=' + str(self.out) + '=out']
        if language == 'cxx':
            # Soong's C++ defaults: no exceptions, and RTTI only where a module asks (rtti: true: libc++abi, ICU).
            common += ['-nostdinc++', '-fno-exceptions', '-frtti' if module.props.get('rtti') else '-fno-rtti',
                       '-std=' + module.props.get('cpp_std', 'c++17').replace('gnu++', 'gnu++')]
        elif language == 'c':
            common += ['-std=' + module.props.get('c_std', 'gnu11')]
        # BoringSSL in FIPS mode needs the APEX build's post-link inject_bssl_hash step, which writes the module's
        # integrity hash into the library; without it the self-test fails. Linked into Cronet here, it is
        # built as ordinary BoringSSL.
        flags = common + [f for f in module.get('cflags') if f != '-DBORINGSSL_FIPS']
        if language == 'cxx':
            flags += module.get('cppflags')
        elif language == 'c':
            flags += module.get('conlyflags')
        else:
            flags += module.get('asflags')
        flags += ['-I' + str(self.overlay)] + ['-I' + str(d) for d in self.includes(module)]
        flags += ['-I' + str(self.out / 'stub-include')]  # gtest/gtest_prod.h (libgtest_prod_headers)
        # Flags name files from the top of an AOSP tree (-fprofile-list=external/cronet/...); absolute paths
        # (gen directories under .../external/cronet/...) are left alone.
        return [re.sub(r'(^|=)external/cronet/', lambda m: m.group(1) + str(self.cronet) + '/', f)
                if not f.startswith('-ffile-prefix-map') else f for f in flags]

    def write_ninja(self):
        llvm = self.llvm
        lines = ['ninja_required_version = 1.7', 'builddir = ' + str(self.out),
                 'rule cc\n  command = %s $flags -MD -MF $out.d -c $in -o $out\n  depfile = $out.d\n  deps = gcc' % (llvm / 'clang'),
                 'rule cxx\n  command = %s $flags -MD -MF $out.d -c $in -o $out\n  depfile = $out.d\n  deps = gcc' % (llvm / 'clang++'),
                 'rule ar\n  command = rm -f $out && %s rcsD $out @$out.rsp\n  rspfile = $out.rsp\n  rspfile_content = $in' % (llvm / 'llvm-ar'),
                 'rule link\n  command = %s $flags @$out.rsp $libs -o $out\n  rspfile = $out.rsp\n  rspfile_content = $in' % (llvm / 'clang++')]
        archives = {}
        target_objects = []
        plan = collections.Counter()
        for key in self.order:
            module = self.modules[key]
            if not module.kind.startswith('cc_library') and module.kind != 'cc_object':
                continue
            objects = []
            for source in self.sources(module):
                language = {'.c': 'c', '.S': 'asm', '.s': 'asm'}.get(source.suffix, 'cxx')
                rel = source.relative_to(self.out) if source.is_relative_to(self.out) else source.relative_to(self.cronet)
                obj = self.out / 'obj' / module.name / (str(rel) + '.o')
                flags = ' '.join(shlex.quote(f) for f in self.flags(module, language))
                lines.append('build %s: %s %s\n  flags = %s' % (obj, 'cc' if language != 'cxx' else 'cxx', source, flags))
                objects.append(obj)
                plan[language] += 1
            if key == self.bp.resolve(TARGET):
                target_objects = objects
            elif objects:
                archive = self.out / 'lib' / ('lib' + module.name + '.a')
                lines.append('build %s: ar %s' % (archive, ' '.join(str(o) for o in objects)))
                archives[key] = archive
        target = self.modules[self.bp.resolve(TARGET)]
        whole = []
        for ref in target.get('whole_static_libs'):
            dep = self.bp.resolve(ref, target.dir)
            if dep in archives:
                whole.append(archives[dep])
        others = [a for k, a in archives.items() if a not in whole]
        stem = target.props.get('stem', 'libmainlinecronet')
        library = self.out / (stem + '.so')
        ldflags = [f.replace('external/cronet/', str(self.cronet) + '/') for f in target.get('ldflags')]
        builtins = sorted(self.args.ndk.resolve().glob(
            'toolchains/llvm/prebuilt/linux-x86_64/lib64/clang/*/lib/linux/libclang_rt.builtins-aarch64-android.a'))
        platform_libs = sorted({'-l' + PLATFORM[p] for p in self.platform if PLATFORM.get(p)} | {'-lc', '-lm', '-ldl'})
        # The Android driver links the NDK's libunwind (-l:libunwind.a) with C++; it lives beside the NDK's builtins.
        unwind = sorted(self.args.ndk.resolve().glob(
            'toolchains/llvm/prebuilt/linux-x86_64/lib64/clang/*/lib/linux/aarch64/libunwind.a'))
        # Only the JNI surface is exported. BoringSSL, linked in, would otherwise export its whole API (built with
        # BORINGSSL_SHARED_LIBRARY), and a process that loads this library globally would see AES_*, SSL_* and the
        # rest interpose an app's own OpenSSL or BoringSSL.
        exports = self.out / 'exports.map'
        exports.write_text('{\n  global:\n    JNI_OnLoad;\n    JNI_OnUnload;\n    Java_*;\n  local:\n    *;\n};\n')
        link_flags = ['--target=aarch64-linux-android%d' % API, '--sysroot=' + str(self.sysroot), '-fuse-ld=lld',
                      '-Wl,--version-script,' + str(exports),
                      '-L' + str(unwind[-1].parent) if unwind else '-Wl,--no-undefined',
                      '-shared', '-nostdlib++', '-Wl,-soname,' + stem + '.so', '-Wl,--build-id=sha1',
                      '-Wl,--no-undefined', '-Wl,-z,relro', '-Wl,-z,now', '-Wl,--hash-style=gnu'] + ldflags
        libs = (['-Wl,--whole-archive'] + [str(a) for a in whole] + ['-Wl,--no-whole-archive', '-Wl,--start-group']
                + [str(a) for a in others] + ['-Wl,--end-group'] + [str(b) for b in builtins[-1:]] + platform_libs)
        lines.append('build %s: link %s | %s\n  flags = %s\n  libs = %s' % (
            library, ' '.join(str(o) for o in target_objects), ' '.join(str(a) for a in archives.values()),
            ' '.join(shlex.quote(f) for f in link_flags), ' '.join(shlex.quote(f) for f in libs)))
        lines.append('default ' + str(library))
        (self.out / 'build.ninja').write_text('\n'.join(lines) + '\n')
        print('ninja: %d archives, %d objects %s -> %s' % (len(archives), sum(plan.values()), dict(plan), library.name))
        return library


# Imports whose Bionic ABI differs from OH musl's, renamed to the Bionic shim's equal-length entry points
# (framework/webview-shim/webview_bionic_shim.c), as the WebView engine's packaging renames them: musl's struct
# addrinfo swaps ai_addr and ai_canonname, its sigset_t is 128 bytes to Bionic's 8, and struct sigaction and
# jmp_buf differ too. Unrenamed, the library's lookups bound to musl's getaddrinfo, whose answers Chromium read with
# Bionic's layout: every name failed to resolve (ERR_NAME_NOT_RESOLVED), and the Play Store could not reach its
# servers. Names the library does not import are skipped.
OH_IMPORT_REWRITES = {
    'connect': 'wl_conn',
    'freeaddrinfo': 'wl_freeai_oh',
    'getaddrinfo': 'wl_getai_oh',
    'getprogname': 'wl_progname',
    'longjmp': 'wl_ljmp',
    'pthread_sigmask': 'wl_pthread_mask',
    'setjmp': 'wl_sjp',
    'sigaction': 'wl_sigact',
    'sigaddset': 'wl_addset',
    'sigemptyset': 'wl_emptyset',
    'sigfillset': 'wl_fillset',
    'sigismember': 'wl_ismember',
}


def rewrite_imports(image, undefined):
    """Renames OH_IMPORT_REWRITES' names in an ELF64's .dynstr, in place; returns {name: [replacement, offset]}.

    A name is renamed only where it is a whole .dynstr entry and an undefined symbol, so neither another name ending
    in it nor an export of the same spelling changes."""
    import struct
    if image[:6] != b'\x7fELF\x02\x01':
        raise ValueError('expected a little-endian ELF64 library')
    shoff, = struct.unpack_from('<Q', image, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', image, 0x3a)
    sections = [struct.unpack_from('<IIQQQQ', image, shoff + i * shentsize) for i in range(shnum)]
    names_offset = sections[shstrndx][4]
    dynstr = None
    for name, _, _, _, offset, size in sections:
        end = image.index(b'\0', names_offset + name)
        if image[names_offset + name:end] == b'.dynstr':
            dynstr = (offset, size)
    if dynstr is None:
        raise ValueError('no .dynstr')
    start, size = dynstr
    rewritten = {}
    for old, new in sorted(OH_IMPORT_REWRITES.items()):
        if len(old) != len(new):
            raise ValueError('import rewrite changes the string length: ' + old)
        if old not in undefined:
            continue
        found = [m.start() for m in re.finditer(b'(?<=\0)' + re.escape(old.encode()) + b'(?=\0)',
                                                bytes(image[start - 1:start + size]))]
        if len(found) != 1:
            raise ValueError('%s is %d .dynstr entries' % (old, len(found)))
        offset = start - 1 + found[0]
        image[offset:offset + len(new)] = new.encode()
        rewritten[old] = [new, offset]
    return rewritten


def stage(library, llvm, out):
    """The library as Westlake deploys it: stripped, with its OH_IMPORT_REWRITES applied, recorded in
    <out>/artifacts.json (the runtime-library build layout: lib/<name> and its sha256)."""
    import hashlib
    staged = out / 'lib' / library.name
    staged.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([str(llvm / 'llvm-strip'), '--strip-unneeded', '-o', str(staged), str(library)], check=True)
    nm = subprocess.run([str(llvm / 'llvm-nm'), '-D', '--undefined-only', str(staged)], check=True,
                        capture_output=True, text=True).stdout
    undefined = {line.split()[-1].split('@')[0] for line in nm.splitlines() if line.strip()}
    image = bytearray(staged.read_bytes())
    rewritten = rewrite_imports(image, undefined)
    staged.write_bytes(image)
    report = {'errors': [], 'artifacts': {library.name: {
        'sha256': hashlib.sha256(image).hexdigest(), 'bytes': len(image), 'import_rewrites': rewritten}}}
    (out / 'artifacts.json').write_text(json.dumps(report, indent=1) + '\n')
    return staged, rewritten


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--cronet', type=Path, required=True)
    parser.add_argument('--ndk', type=Path, required=True)
    parser.add_argument('--llvm', type=Path, required=True, help="Chromium's clang bin directory (clang 16 or newer)")
    parser.add_argument('--protoc', type=Path, required=True, help='host protoc of the version Cronet vendors (3.20.x)')
    parser.add_argument('--javap', type=Path, required=True, help="a JDK's javap (jni_zero's from-jar headers)")
    parser.add_argument('--android-jar', type=Path, required=True, help="an Android SDK platform's android.jar")
    parser.add_argument('--ninja', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--patches', type=Path, default=Path(__file__).resolve().parent.parent / 'native/cronet-patches',
                        help="Westlake's source patches (default: native/cronet-patches)")
    parser.add_argument('--jobs', type=int, default=os.cpu_count() or 8)
    parser.add_argument('--plan-only', action='store_true', help='resolve the closure and stop')
    args = parser.parse_args()
    build = Build(args)
    kinds = collections.Counter(m.kind for m in build.modules.values())
    print('closure: %d modules %s; platform libraries %s' % (len(build.modules), dict(kinds), sorted(build.platform)))
    if args.plan_only:
        return
    args.out.mkdir(parents=True, exist_ok=True)
    # libgtest_prod_headers: gtest/gtest_prod.h, which production code includes for FRIEND_TEST only.
    stub = build.out / 'stub-include' / 'gtest' / 'gtest_prod.h'
    stub.parent.mkdir(parents=True, exist_ok=True)
    stub.write_text('#pragma once\n#define FRIEND_TEST(test_case_name, test_name) '
                    'friend class test_case_name##_##test_name##_Test\n')
    build.apply_patches()
    build.run_genrules()
    library = build.write_ninja()
    subprocess.run([str(args.ninja), '-C', str(build.out), '-j', str(args.jobs), '-k', '0'], check=True)
    record = {'library': library.name, 'bytes': library.stat().st_size,
              'cronet_version': library.name[len('libmainlinecronet.'):-len('.so')]}
    (build.out / 'cronet-native.json').write_text(json.dumps(record, indent=2) + '\n')
    print('built', library)
    staged, rewritten = stage(library, args.llvm, build.out / 'stage')
    print('staged', staged, 'imports renamed:', ' '.join(sorted(rewritten)))


if __name__ == '__main__':
    main()
