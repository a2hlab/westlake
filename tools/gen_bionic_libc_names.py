#!/usr/bin/env python3
"""gen_bionic_libc_names.py LIBC_MAP OUT_HEADER

Writes framework/webview-shim/bionic_libc_names.h: the names Bionic's libc.so exports to apps on arm64, from AOSP
bionic's libc/libc.map.txt (version blocks LIBC and LIBC_N .. LIBC_V; not LIBC_PRIVATE, LIBC_PLATFORM or
LIBC_DEPRECATED; an entry tagged with architectures counts only when arm64 is one of them), sorted in strcmp order
for a binary search. The bionic shim's dlsym uses it to recognise a name Android's libc would answer.
"""
import re
import sys

ARCHES = {'arm', 'arm64', 'x86', 'x86_64', 'riscv64'}
PUBLIC = re.compile(r'^LIBC(_[NOPQRSTUV])?$')


def names(path):
    found, block = set(), None
    for raw in open(path, encoding='utf-8'):
        line = raw.strip()
        opening = re.match(r'^([A-Z_]+)\s*\{', line)
        if opening:
            block = opening.group(1)
            continue
        if line.startswith('}'):
            block = None
            continue
        if block is None or not PUBLIC.match(block):
            continue
        entry = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)\s*;\s*(?:#\s*(.*))?$', line)
        if not entry:
            continue
        arches = {tag for tag in (entry.group(2) or '').split() if tag in ARCHES}
        if arches and 'arm64' not in arches:
            continue
        found.add(entry.group(1))
    return sorted(found, key=lambda name: name.encode())


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    listed = names(sys.argv[1])
    with open(sys.argv[2], 'w', encoding='utf-8') as out:
        out.write('/*\n'
                  ' * Generated by tools/gen_bionic_libc_names.py from AOSP bionic libc/libc.map.txt\n'
                  ' * (android-platform-15.0.0_r18): the %d names libc.so exports to apps on arm64, in strcmp\n'
                  ' * order. Do not edit; generate it again.\n'
                  ' */\n' % len(listed))
        out.write('static const char *const westlake_bionic_libc_names[] = {\n')
        for name in listed:
            out.write('    "%s",\n' % name)
        out.write('};\n')


if __name__ == '__main__':
    main()
